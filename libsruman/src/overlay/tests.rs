#[test]
fn scout_libraries_come_from_its_steam_runtime_directory() {
    let tmp = tempfile::tempdir().unwrap();
    let build = tmp.path();
    let lib = build.join(format!("steam-runtime/lib/{X64}"));
    let usr = build.join(format!("steam-runtime/usr/lib/{X64}"));
    fs::create_dir_all(&lib).unwrap();
    fs::create_dir_all(&usr).unwrap();
    fs::write(lib.join("libpng12.so.0.46.0"), "png").unwrap();
    symlink("libpng12.so.0.46.0", lib.join("libpng12.so.0")).unwrap();
    // The same name in usr/lib loses to lib/, as in `run.sh`.
    fs::write(usr.join("libpng12.so.0"), "other").unwrap();
    fs::write(usr.join("libgtk-x11-2.0.so.0"), "gtk").unwrap();
    symlink("nowhere", usr.join("libdangling.so.1")).unwrap();

    // No mtree: the directories themselves.
    let libs = runtime_libs(build, Entry::ScoutOnSoldier, &[Abi::X86_64, Abi::I386]).unwrap();
    let names: Vec<&str> = libs.iter().map(|l| l.name.as_str()).collect();
    assert_eq!(names, ["libpng12.so.0", "libgtk-x11-2.0.so.0"]);
    assert_eq!(libs[0].file, lib.join("libpng12.so.0.46.0"));
    assert_eq!(libs[0].real_name, "libpng12.so.0.46.0");

    // With one: the mtree.
    write_mtree(
        &build.join("mtree.txt.gz"),
        &format!(
            "#mtree\n./steam-runtime/lib/{X64}/libpng12.so.0.46.0 type=file\n\
             ./steam-runtime/lib/{X64}/libpng12.so.0 type=link link=libpng12.so.0.46.0\n"
        ),
    );
    let libs = runtime_libs(build, Entry::ScoutOnSoldier, &[Abi::X86_64]).unwrap();
    let names: Vec<&str> = libs.iter().map(|l| l.name.as_str()).collect();
    assert_eq!(names, ["libpng12.so.0"]);
}

fn lib(abi: Abi, name: &str, file: &Path) -> RuntimeLib {
    RuntimeLib {
        abi,
        name: name.to_owned(),
        file: file.to_path_buf(),
        real_name: file.file_name().unwrap().to_string_lossy().into_owned(),
    }
}

#[test]
fn newest_wins_and_glibc_and_gpu_stay_on_the_host() {
    let tmp = tempfile::tempdir().unwrap();
    let rt = tmp.path().join("rt");
    fs::create_dir_all(&rt).unwrap();
    let file = |name: &str, contents: &str| {
        let path = rt.join(name);
        fs::write(&path, contents).unwrap();
        path
    };
    let host = fake_host(
        &tmp.path().join("host"),
        &[
            (
                "libc6,x86-64",
                "libwayland-client.so.0",
                "libwayland-client.so.0.24.0",
                "",
            ),
            (
                "libc6,x86-64",
                "libSDL2-2.0.so.0",
                "libSDL2-2.0.so.0.3200.56",
                "",
            ),
            ("libc6,x86-64", "libz.so.1", "libz.so.1.3.1", ""),
            (
                "libc6,x86-64",
                "libgcc_s.so.1",
                "libgcc_s.so.1",
                "GCC_3.0\0GCC_14.0.0\0",
            ),
            ("libc6,x86-64", "libstdc++.so.6", "libstdc++.so.6.0.34", ""),
        ],
    );
    let libs = [
        // Older than the host's: the host's.
        lib(
            Abi::X86_64,
            "libwayland-client.so.0",
            &file("libwayland-client.so.0.23.1", ""),
        ),
        // Newer: the runtime's.
        lib(
            Abi::X86_64,
            "libSDL2-2.0.so.0",
            &file("libSDL2-2.0.so.0.3200.74", ""),
        ),
        // The same: the host's.
        lib(Abi::X86_64, "libz.so.1", &file("libz.so.1.3.1", "")),
        // Not on the host: the runtime's.
        lib(
            Abi::X86_64,
            "libpng16.so.16",
            &file("libpng16.so.16.37.0", ""),
        ),
        lib(Abi::I386, "libz.so.1", &file("i386-libz.so.1.3.1", "")),
        // Same file name: GCC_ nodes decide.
        lib(
            Abi::X86_64,
            "libgcc_s.so.1",
            &file("libgcc_s.so.1", "GCC_3.0\0GCC_15.1.0\0"),
        ),
        lib(
            Abi::X86_64,
            "libstdc++.so.6",
            &file("libstdc++.so.6.0.33", ""),
        ),
        // Never.
        lib(Abi::X86_64, "libc.so.6", &file("libc.so.6", "")),
        lib(
            Abi::X86_64,
            "libvulkan.so.1",
            &file("libvulkan.so.1.4.309", ""),
        ),
        lib(Abi::X86_64, "libdrm.so.2", &file("libdrm.so.2.124.0", "")),
    ];
    let base = tmp.path().join("overlays");
    let abis = [Abi::X86_64, Abi::I386];
    let plan = plan(&libs, &host, &BTreeMap::new(), &abis, &base);
    let linked: Vec<(Abi, &str)> = plan
        .links
        .iter()
        .flat_map(|(abi, names)| names.keys().map(move |n| (*abi, n.as_str())))
        .collect();
    assert_eq!(
        linked,
        [
            (Abi::X86_64, "libSDL2-2.0.so.0"),
            (Abi::X86_64, "libgcc_s.so.1"),
            (Abi::X86_64, "libpng16.so.16"),
            (Abi::I386, "libz.so.1"),
        ]
    );
    assert!(plan.overrides.is_empty());
    assert_eq!(plan.dir.parent(), Some(base.as_path()));
    assert_eq!(
        plan.ld_library_path(),
        OsString::from(format!(
            "{}:{}",
            plan.dir.join(X64).display(),
            plan.dir.join(X86).display()
        ))
    );

    // Overrides: SDL from the host, wayland from the runtime.
    let overrides = BTreeMap::from([
        ("libSDL2-2.0.so.0".to_owned(), LibOverride::Host),
        ("libwayland-client.so.0".to_owned(), LibOverride::Runtime),
        ("libnothere.so.1".to_owned(), LibOverride::Newest),
    ]);
    let other = super::plan(&libs, &host, &overrides, &abis, &base);
    let x64: Vec<&str> = other.links[&Abi::X86_64]
        .keys()
        .map(String::as_str)
        .collect();
    assert_eq!(
        x64,
        ["libgcc_s.so.1", "libpng16.so.16", "libwayland-client.so.0"]
    );
    assert_ne!(other.dir, plan.dir, "other links, other folder");
    let report = |name: &str, abi| {
        other
            .overrides
            .iter()
            .find(|r| r.name == name && r.abi == abi)
            .unwrap()
            .resolved
            .clone()
    };
    assert_eq!(
        report("libSDL2-2.0.so.0", Abi::X86_64),
        Resolved::Host(tmp.path().join("host/lib/libSDL2-2.0.so.0"))
    );
    assert_eq!(
        report("libwayland-client.so.0", Abi::X86_64),
        Resolved::Runtime(rt.join("libwayland-client.so.0.23.1"))
    );
    assert_eq!(report("libnothere.so.1", Abi::X86_64), Resolved::Missing);
    assert_eq!(report("libSDL2-2.0.so.0", Abi::I386), Resolved::Missing);
    assert_eq!(other.overrides.len(), 6, "every override, per ABI");

    // The same inputs give the same folder.
    assert_eq!(
        super::plan(&libs, &host, &BTreeMap::new(), &abis, &base).dir,
        plan.dir
    );
}

#[test]
fn the_folder_is_built_once_with_a_link_per_library() {
    let tmp = tempfile::tempdir().unwrap();
    let target = tmp.path().join("libSDL2-2.0.so.0.3200.74");
    fs::write(&target, "").unwrap();
    let plan = OverlayPlan {
        dir: tmp.path().join("overlays/sniper/1/abc"),
        links: BTreeMap::from([(
            Abi::X86_64,
            BTreeMap::from([("libSDL2-2.0.so.0".to_owned(), target.clone())]),
        )]),
        abis: vec![Abi::X86_64, Abi::I386],
        overrides: Vec::new(),
    };
    plan.build().unwrap();
    assert_eq!(
        fs::read_link(plan.dir.join(X64).join("libSDL2-2.0.so.0")).unwrap(),
        target
    );
    assert!(plan.dir.join(X86).is_dir(), "empty, but on the path");
    // Built already: left alone, and no temporary folders stay behind.
    fs::write(plan.dir.join("marker"), "").unwrap();
    plan.build().unwrap();
    assert!(plan.dir.join("marker").exists());
    let left: Vec<_> = fs::read_dir(plan.dir.parent().unwrap())
        .unwrap()
        .flatten()
        .map(|e| e.file_name())
        .collect();
    assert_eq!(left, [OsString::from("abc")]);

    // A file where the folder's parent should be: an error, nothing left.
    let blocked = OverlayPlan {
        dir: tmp.path().join("file/abc"),
        ..plan
    };
    fs::write(tmp.path().join("file"), "").unwrap();
    assert!(blocked.build().is_err());
}

#[test]
fn glibc_versions_are_compared_by_version_nodes() {
    let tmp = tempfile::tempdir().unwrap();
    let runtime_libc = tmp.path().join("libc.so.6");
    fs::write(
        &runtime_libc,
        b"GLIBC_2.2.5\0GLIBC_2.31\0GLIBC_PRIVATE\0GLIBC_2.9\0",
    )
    .unwrap();
    let libs = [lib(Abi::X86_64, "libc.so.6", &runtime_libc)];
    let newer = fake_host(
        &tmp.path().join("new"),
        &[(
            "libc6,x86-64",
            "libc.so.6",
            "libc.so.6",
            "GLIBC_2.2.5\0GLIBC_2.42\0",
        )],
    );
    assert_eq!(glibc_problem(&libs, &newer, Abi::X86_64), None);
    let older = fake_host(
        &tmp.path().join("old"),
        &[(
            "libc6,x86-64",
            "libc.so.6",
            "libc.so.6",
            "GLIBC_2.2.5\0GLIBC_2.28\0",
        )],
    );
    assert_eq!(
        glibc_problem(&libs, &older, Abi::X86_64).unwrap(),
        "overlay mode needs the host's glibc to be at least the runtime's: the runtime has \
         2.31, the host 2.28; use `mode = \"container\"`"
    );
    // Scout ships no libc: nothing to compare.
    assert_eq!(glibc_problem(&[], &older, Abi::X86_64), None);
    assert_eq!(max_version_node(&runtime_libc, "GLIBC_"), Some(vec![2, 31]));
    assert_eq!(max_version_node(&tmp.path().join("none"), "GLIBC_"), None);
}

