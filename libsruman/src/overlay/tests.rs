use std::{fs, io::Write, os::unix::fs::symlink};

use super::*;

/// Writes `text` as a gzipped mtree.
pub(crate) fn write_mtree(path: &Path, text: &str) {
    let mut gz =
        flate2::write::GzEncoder::new(fs::File::create(path).unwrap(), flate2::Compression::fast());
    gz.write_all(text.as_bytes()).unwrap();
    gz.finish().unwrap();
}

/// A container build's platform with libraries the way Valve ships them:
/// real files only, the soname links in `usr-mtree.txt.gz`.
/// `libs`: (abi triplet, soname, real file name, contents).
pub(crate) fn fake_platform(build_dir: &Path, platform: &str, libs: &[(&str, &str, &str, &str)]) {
    let platform = build_dir.join(platform);
    let files = platform.join("files");
    let mut mtree = String::from("#mtree\n. type=dir\n./lib type=dir\n");
    for (triplet, soname, real, contents) in libs {
        let dir = files.join("lib").join(triplet);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join(real), contents).unwrap();
        mtree.push_str(&format!(
            "./lib/{triplet}/{real} type=file size={}\n",
            contents.len()
        ));
        if soname != real {
            mtree.push_str(&format!("./lib/{triplet}/{soname} type=link link={real}\n"));
        }
    }
    write_mtree(&platform.join("usr-mtree.txt.gz"), &mtree);
}

/// `ldconfig -p` output for host files under `dir`: (flags, name, real
/// file name, contents). Each name is a link to its real file, as on a
/// real system.
pub(crate) fn fake_host(dir: &Path, libs: &[(&str, &str, &str, &str)]) -> HostLibs {
    let mut text = format!("{} libs found in cache `/etc/ld.so.cache'\n", libs.len());
    for (flags, name, real, contents) in libs {
        let sub = dir.join(if flags.contains("64") { "lib" } else { "lib32" });
        fs::create_dir_all(&sub).unwrap();
        fs::write(sub.join(real), contents).unwrap();
        if name != real {
            let _ = symlink(real, sub.join(name));
        }
        text.push_str(&format!(
            "\t{name} ({flags}) => {}\n",
            sub.join(name).display()
        ));
    }
    HostLibs::parse(&text)
}

const X64: &str = "x86_64-linux-gnu";
const X86: &str = "i386-linux-gnu";

#[test]
fn ldconfig_output_is_parsed_by_abi_and_first_entry_wins() {
    let host = HostLibs::parse(
        "5 libs found in cache `/etc/ld.so.cache'\n\
         \tlibz.so.1 (libc6,x86-64) => /usr/lib/libz.so.1\n\
         \tlibz.so.1 (libc6,x86-64) => /opt/lib/libz.so.1\n\
         \tlibz.so.1 (libc6) => /usr/lib32/libz.so.1\n\
         \tlibz.so.1 (libc6,x32) => /usr/libx32/libz.so.1\n\
         \tlibfoo.so.2 (libc6,AArch64) => /usr/lib/aarch64/libfoo.so.2\n\
         Cache generated by: ldconfig (GNU libc) stable release version 2.42\n",
    );
    assert_eq!(
        host.get(Abi::X86_64, "libz.so.1"),
        Some(Path::new("/usr/lib/libz.so.1"))
    );
    assert_eq!(
        host.get(Abi::I386, "libz.so.1"),
        Some(Path::new("/usr/lib32/libz.so.1"))
    );
    assert_eq!(
        host.get(Abi::Aarch64, "libfoo.so.2"),
        Some(Path::new("/usr/lib/aarch64/libfoo.so.2"))
    );
    assert_eq!(host.libs.len(), 3, "x32 is skipped: {host:?}");
}

#[test]
