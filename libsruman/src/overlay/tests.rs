/// Steam's real steamrt4 and scout with the real host: the host's GPU tools
/// must see the same devices through the overlay as without it (D13: an
/// older runtime library first breaks the host's drivers).
#[test]
#[ignore = "needs Steam's SteamLinuxRuntime_4 and SteamLinuxRuntime, a GPU and a display"]
fn real_runtimes_keep_the_host_gpu_stack_working() {
    let home = std::env::var_os("HOME").unwrap();
    let common = Path::new(&home).join(".local/share/Steam/steamapps/common");
    let host = HostLibs::system().unwrap();
    let abis = Abi::for_arch(Arch::current().unwrap());
    let tmp = tempfile::tempdir().unwrap();
    let devices = |path: Option<&OsString>, program: &str, args: &[&str], keys: &[&str]| {
        let mut cmd = Command::new(program);
        cmd.args(args);
        if let Some(path) = path {
            cmd.env("LD_LIBRARY_PATH", path);
        }
        let out = cmd.output().unwrap();
        let text = String::from_utf8_lossy(&out.stdout).into_owned()
            + &String::from_utf8_lossy(&out.stderr);
        let mut lines: Vec<String> = text
            .lines()
            .filter(|l| keys.iter().any(|k| l.contains(k)))
            .map(|l| l.trim().to_owned())
            .collect();
        lines.dedup();
        lines
    };
    for (dir, entry) in [
        (common.join("SteamLinuxRuntime_4"), Entry::Container),
        (common.join("SteamLinuxRuntime"), Entry::ScoutOnSoldier),
    ] {
        let libs = runtime_libs(&dir, entry, abis).unwrap();
        assert!(
            libs.len() > 100,
            "{}: {} libraries",
            dir.display(),
            libs.len()
        );
        let plan = plan(&libs, &host, &BTreeMap::new(), abis, tmp.path());
        plan.build().unwrap();
        let path = plan.ld_library_path();
        for (program, args, keys) in [
            (
                "vulkaninfo",
                &["--summary"][..],
                &["deviceName", "driverName", "ERROR"][..],
            ),
            ("eglinfo", &["-B"][..], &["renderer", "error"][..]),
            ("glxinfo", &["-B"][..], &["renderer string", "error"][..]),
        ] {
            let plain = devices(None, program, args, keys);
            let overlaid = devices(Some(&path), program, args, keys);
            assert!(!plain.is_empty(), "{program} found nothing");
            assert_eq!(overlaid, plain, "{program} through {}", dir.display());
        }
        eprintln!(
            "{}: {} libraries, {} linked",
            dir.display(),
            libs.len(),
            plan.links.values().map(BTreeMap::len).sum::<usize>()
        );
    }
}
